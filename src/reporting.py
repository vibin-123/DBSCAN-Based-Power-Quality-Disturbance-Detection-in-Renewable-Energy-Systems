"""Builds ``outputs/reports/results_report.md`` from the stored result tables.

Every number in the report is read from ``outputs/results``; nothing is typed
by hand.   Run:  python -m src.reporting
"""
from __future__ import annotations

import json

import pandas as pd

from . import config as C


def _csv(name: str, **kw) -> pd.DataFrame:
    return pd.read_csv(C.RESULTS / f"{name}.csv", **kw)


def _md(df: pd.DataFrame, digits: int = 3, index: bool = False) -> str:
    d = df.copy()
    if index:
        d = d.reset_index()
    num = d.select_dtypes("number").columns
    d[num] = d[num].round(digits)
    head = "| " + " | ".join(map(str, d.columns)) + " |"
    sep = "|" + "---|" * len(d.columns)
    rows = ["| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |"
            for r in d.itertuples(index=False)]
    return "\n".join([head, sep] + rows)


def experiment_section(name: str, title: str, s: dict) -> list[str]:
    f, s1, s2 = s["final"], s["stage1"], s["stage2"]
    prof = _csv(f"{name}_cluster_profile")
    keep = ["name", "n_windows", "share_pct", "n_days", "v_dev_pct", "v_std_pct",
            "rvc_max_pct", "vuf_pct", "thd_u_pct", "u_h5_pct", "thd_i_pct",
            "i_rms_a", "p_kw", "hour_local", "weekend_share_pct",
            "vre_penetration_pct", "solar_penetration_pct", "wind_penetration_pct"]
    rate = _csv(f"{name}_unusual_rate_by_re_level")
    ratel = _csv(f"{name}_unusual_rate_by_local_pv_level")
    perm = _csv(f"{name}_permutation_tests").rename(columns={"Unnamed: 0": "test"})
    stab = _csv(f"{name}_stability")
    out = [f"## {title}", "",
           f"Inputs ({s['dimensions']}): {', '.join(s['features'])}.", "",
           f"- Windows clustered: {s['n_windows']:,}.",
           f"- Stage 1: MinPts = {s1['min_samples']}, epsilon = {s1['eps']:.3f} "
           f"(knee). Result: {s1['n_clusters']} cluster(s), {s1['noise_pct']:.2f} % noise.",
           f"- Stage 2 on the {s2['n_input_windows']:,} stage-1 noise windows: "
           f"MinPts = {s2['min_samples']}, epsilon = {s2['eps']:.3f}. Result: "
           f"{s2['n_clusters']} cluster(s); silhouette {s2['silhouette']:.3f}, "
           f"Davies-Bouldin {s2['davies_bouldin']:.3f} (clustered stage-2 points only).",
           f"- Final: {f['n_clusters']} clusters, dominant cluster "
           f"{f['dominant_cluster_pct']:.2f} %, unusual windows {f['unusual_pct']:.2f} %, "
           f"isolated noise {f['isolated_noise_pct']:.2f} %. Silhouette over all "
           f"clustered points {f['silhouette']:.3f}, Davies-Bouldin {f['davies_bouldin']:.3f}.",
           f"- Consecutive unusual episodes: {s['unusual_episodes']['count']}, median "
           f"{s['unusual_episodes']['median_duration_min']:.0f} min, longest "
           f"{s['unusual_episodes']['max_duration_min']:.0f} min.", "",
           "### Cluster profile (medians)", "",
           _md(prof[[c for c in keep if c in prof.columns]], 2), "",
           "### Unusual-window rate by regional renewable level", "",
           _md(rate, 4), "",
           "### Unusual-window rate by local PV level (1 Jan - 9 Apr 2024)", "",
           _md(ratel, 4), "",
           "### Label share within each regional level (%)", "",
           _md(_csv(f"{name}_cluster_by_re_level_colpct"), 3), "",
           "### Whole-day permutation tests", "",
           _md(perm, 4), "",
           "### Stability (80 % subsamples, 20 rounds)", "",
           _md(stab.drop(columns="round").agg(["mean", "min", "max"]), 3, index=True), "",
           "### Stage-1 parameter sensitivity", "",
           _md(_csv(f"{name}_sensitivity_stage1").drop(columns=["metric", "knee_eps"]), 3), "",
           "### Stage-2 parameter sensitivity", "",
           _md(_csv(f"{name}_sensitivity_stage2").drop(columns=["metric", "knee_eps"]), 3), "",
           "### Distance metric comparison (stage 1)", "",
           _md(_csv(f"{name}_metric_comparison"), 3), "",
           "### Scaler comparison", "",
           "```json", json.dumps(s["scaler_comparison"], indent=1), "```", "",
           "### K-Means and Ward reference (8,000-window subsample)", "",
           _md(_csv(f"{name}_baseline_kmeans_ward"), 3), ""]
    return out


def main() -> None:
    summ = json.loads((C.RESULTS / "summary.json").read_text())
    cmp_ = json.loads((C.RESULTS / "comparison.json").read_text())
    lines = ["# Results report", "",
             "Generated by `src/reporting.py` from the tables in `outputs/results`. "
             "All data are real measurements (SPARK, SMARD), year 2024.", "",
             "Reading guide: label 0 is the dominant dense cluster; `U` labels are "
             "clusters found among the stage-1 noise; -1 is isolated noise. "
             "'Unusual' means any label other than 0. Unusual does not mean "
             "non-compliant: every 10-minute mean is inside EN 50160 limits.", ""]
    lines += experiment_section("exp1", "Experiment 1: power quality only", summ["exp1"])
    lines += ["### Robustness of the renewable-level contrast to DBSCAN parameters", "",
              _md(_csv("exp1_association_robustness"), 3), "",
              "### Power-quality indicators by regional level", "",
              _md(_csv("exp1_pq_by_re_level"), 3), "",
              "### Kruskal-Wallis across regional levels", "",
              _md(_csv("exp1_kruskal_re_level"), 4), ""]
    lines += experiment_section("exp2", "Experiment 2: power quality + renewables",
                                summ["exp2"])
    lines += ["## Experiment 1 versus Experiment 2", "",
              _md(_csv("comparison_summary").set_index("experiment").T, 3, index=True), "",
              f"Agreement on shared windows: adjusted Rand index {cmp_['ari']:.3f}; "
              f"Jaccard of the unusual sets {cmp_['unusual_jaccard']:.3f} "
              f"({cmp_['unusual_both']:,} unusual in both, {cmp_['unusual_only_a']:,} "
              f"only in Experiment 1, {cmp_['unusual_only_b']:,} only in Experiment 2).", "",
              "### Label migration (rows Experiment 1, columns Experiment 2)", "",
              _md(_csv("comparison_migration_exp1_vs_exp2"), 0), "",
              "### Renewable block weight sweep", "",
              _md(_csv("comparison_weight_sweep"), 3), "",
              "## Correlation of PQ indicators with renewable variables", "",
              _md(_csv("correlation_pq_vs_renewables"), 3), ""]
    dest = C.REPORTS / "results_report.md"
    dest.write_text("\n".join(lines))
    print("written", dest)


if __name__ == "__main__":
    main()
